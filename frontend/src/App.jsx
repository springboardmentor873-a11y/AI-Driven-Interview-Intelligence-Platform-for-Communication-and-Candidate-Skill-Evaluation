import { useEffect, useRef, useState } from "react";

const API_BASE_URL = (
  import.meta.env.VITE_API_BASE_URL || "http://localhost:8000/api"
).replace(/\/+$/, "");

const workflow = [
  {
    number: "01",
    title: "Set up your profile",
    description: "Create a secure candidate account.",
    status: "In place",
  },
  {
    number: "02",
    title: "Add your resume",
    description: "Upload a PDF so your skills can guide practice.",
    status: "Next step",
  },
  {
    number: "03",
    title: "Build your interview",
    description: "Generate questions from your role and resume.",
    status: "Next step",
  },
  {
    number: "04",
    title: "Plan an interview",
    description: "Start a guided session and submit your answers.",
    status: "Available",
  },
];

function aiSourceLabel(source) {
  if (source === "gemini") {
    return "Generated by Gemini";
  }
  if (source === "fallback") {
    return "Local deterministic fallback";
  }
  if (source === "not_evaluated") {
    return "Not evaluated";
  }
  return "";
}

async function requestJson(path, { method = "GET", token, body } = {}) {
  const headers = {};

  if (token) {
    headers.Authorization = `Bearer ${token}`;
  }
  if (body && !(body instanceof FormData)) {
    headers["Content-Type"] = "application/json";
  }

  const response = await fetch(`${API_BASE_URL}${path}`, {
    method,
    headers,
    body,
  });
  const data = await response.json().catch(() => null);

  if (!response.ok) {
    const messages = [];
    if (typeof data?.detail === "string") {
      messages.push(data.detail);
    } else if (data && typeof data === "object") {
      Object.values(data).forEach((value) => {
        messages.push(...(Array.isArray(value) ? value : [value]));
      });
    }

    const error = new Error(
      messages.filter((message) => typeof message === "string").join(" ") ||
        `Request failed with status ${response.status}.`,
    );
    error.status = response.status;
    throw error;
  }

  return data;
}

function App() {
  const [accessToken, setAccessToken] = useState(() =>
    sessionStorage.getItem("smarthire.access"),
  );
  const [authChecking, setAuthChecking] = useState(() =>
    Boolean(sessionStorage.getItem("smarthire.access")),
  );
  const [authMode, setAuthMode] = useState("login");
  const [showPassword, setShowPassword] = useState(false);
  const [authError, setAuthError] = useState("");
  const [dashboardError, setDashboardError] = useState("");
  const [profile, setProfile] = useState(null);
  const [resumes, setResumes] = useState([]);
  const [interviews, setInterviews] = useState([]);
  const [selectedInterview, setSelectedInterview] = useState(null);
  const [interviewQuestions, setInterviewQuestions] = useState([]);
  const [answerText, setAnswerText] = useState("");
  const [interviewError, setInterviewError] = useState("");
  const [selectedFile, setSelectedFile] = useState(null);
  const [isSubmitting, setIsSubmitting] = useState(false);
  const [isUploading, setIsUploading] = useState(false);
  const [extractingResumeId, setExtractingResumeId] = useState(null);
  const [resumeAiConsent, setResumeAiConsent] = useState(false);
  const [generationAiConsent, setGenerationAiConsent] = useState(false);
  const [answerAiConsent, setAnswerAiConsent] = useState(false);
  const [isGeneratingInterview, setIsGeneratingInterview] = useState(false);
  const [isStartingInterview, setIsStartingInterview] = useState(false);
  const [isSubmittingAnswer, setIsSubmittingAnswer] = useState(false);
  const fileInputRef = useRef(null);

  useEffect(() => {
    if (!accessToken) {
      setAuthChecking(false);
      return undefined;
    }

    let active = true;
    setAuthChecking(true);

    Promise.all([
      requestJson("/auth/profile/", { token: accessToken }),
      requestJson("/auth/resumes/", { token: accessToken }),
      requestJson("/interviews/", { token: accessToken }),
    ])
      .then(([user, userResumes, userInterviews]) => {
        if (active) {
          setProfile(user);
          setResumes(userResumes);
          setInterviews(userInterviews);
          setDashboardError("");
        }
      })
      .catch((error) => {
        if (!active) {
          return;
        }
        sessionStorage.removeItem("smarthire.access");
        sessionStorage.removeItem("smarthire.refresh");
        setAccessToken(null);
        setProfile(null);
        setResumes([]);
        setInterviews([]);
        setSelectedInterview(null);
        setInterviewQuestions([]);
        setAuthError(
          error.status === 401
            ? "Your session expired. Please sign in again."
            : error.message,
        );
      })
      .finally(() => {
        if (active) {
          setAuthChecking(false);
        }
      });

    return () => {
      active = false;
    };
  }, [accessToken]);

  async function handleAuthSubmit(event) {
    event.preventDefault();
    setAuthError("");
    setIsSubmitting(true);

    const form = new FormData(event.currentTarget);
    const username = String(form.get("username") || "").trim();
    const password = String(form.get("password") || "");

    try {
      if (authMode === "register") {
        await requestJson("/auth/register/", {
          method: "POST",
          body: JSON.stringify({
            username,
            email: String(form.get("email") || "").trim(),
            password,
            first_name: String(form.get("first_name") || "").trim(),
            last_name: String(form.get("last_name") || "").trim(),
          }),
        });
      }

      const tokens = await requestJson("/auth/login/", {
        method: "POST",
        body: JSON.stringify({ username, password }),
      });

      sessionStorage.setItem("smarthire.access", tokens.access);
      sessionStorage.setItem("smarthire.refresh", tokens.refresh);
      setAuthChecking(true);
      setAccessToken(tokens.access);
    } catch (error) {
      setAuthError(error.message);
    } finally {
      setIsSubmitting(false);
    }
  }

  function handleSignOut() {
    sessionStorage.removeItem("smarthire.access");
    sessionStorage.removeItem("smarthire.refresh");
    setAccessToken(null);
    setProfile(null);
    setResumes([]);
    setInterviews([]);
    setSelectedInterview(null);
    setInterviewQuestions([]);
    setSelectedFile(null);
    setResumeAiConsent(false);
    setGenerationAiConsent(false);
    setAnswerAiConsent(false);
    setDashboardError("");
    setInterviewError("");
    setAuthError("");
  }

  async function handleResumeUpload(event) {
    event.preventDefault();
    setDashboardError("");

    if (!selectedFile) {
      setDashboardError("Choose a PDF file to upload.");
      return;
    }
    if (!selectedFile.name.toLowerCase().endsWith(".pdf")) {
      setDashboardError("Choose a file with a .pdf extension.");
      return;
    }
    if (selectedFile.size > 10 * 1024 * 1024) {
      setDashboardError("Resume files must be 10 MB or smaller.");
      return;
    }

    const form = new FormData();
    form.append("file", selectedFile);
    setIsUploading(true);

    try {
      const resume = await requestJson("/auth/resumes/", {
        method: "POST",
        token: accessToken,
        body: form,
      });
      setResumes((current) => [resume, ...current]);
      setSelectedFile(null);
      if (fileInputRef.current) {
        fileInputRef.current.value = "";
      }
    } catch (error) {
      setDashboardError(error.message);
    } finally {
      setIsUploading(false);
    }
  }

  async function handleResumeDownload(resumeId) {
    setDashboardError("");

    try {
      const response = await fetch(
        `${API_BASE_URL}/auth/resumes/${resumeId}/download/`,
        {
          headers: { Authorization: `Bearer ${accessToken}` },
        },
      );
      if (!response.ok) {
        throw new Error(`Download failed with status ${response.status}.`);
      }

      const fileUrl = URL.createObjectURL(await response.blob());
      const link = document.createElement("a");
      link.href = fileUrl;
      link.download = `smarthire-resume-${resumeId}.pdf`;
      document.body.appendChild(link);
      link.click();
      link.remove();
      URL.revokeObjectURL(fileUrl);
    } catch (error) {
      setDashboardError(error.message);
    }
  }

  async function handleResumeDelete(resumeId) {
    if (!window.confirm("Delete this resume?")) {
      return;
    }

    setDashboardError("");
    try {
      await requestJson(`/auth/resumes/${resumeId}/`, {
        method: "DELETE",
        token: accessToken,
      });
      setResumes((current) =>
        current.filter((resume) => resume.id !== resumeId),
      );
      if (selectedInterview?.resume === resumeId) {
        setSelectedInterview(null);
        setInterviewQuestions([]);
      }
    } catch (error) {
      setDashboardError(error.message);
    }
  }

  async function handleResumeSkillExtraction(resumeId) {
    setDashboardError("");
    setExtractingResumeId(resumeId);
    try {
      const resume = await requestJson(
        `/auth/resumes/${resumeId}/extract-skills/`,
        {
          method: "POST",
          token: accessToken,
          body: JSON.stringify({ ai_consent: resumeAiConsent }),
        },
      );
      setResumes((current) =>
        current.map((item) => (item.id === resumeId ? resume : item)),
      );
    } catch (error) {
      setDashboardError(error.message);
    } finally {
      setExtractingResumeId(null);
      setResumeAiConsent(false);
    }
  }

  async function loadInterview(interviewId) {
    const [interview, questions] = await Promise.all([
      requestJson(`/interviews/${interviewId}/`, { token: accessToken }),
      requestJson(`/interviews/${interviewId}/questions/`, {
        token: accessToken,
      }),
    ]);
    setSelectedInterview(interview);
    setInterviewQuestions(questions);
    setAnswerText("");
    return interview;
  }

  async function handleOpenInterview(interviewId) {
    setInterviewError("");
    try {
      await loadInterview(interviewId);
    } catch (error) {
      setInterviewError(error.message);
    }
  }

  async function handleInterviewCreate(event) {
    event.preventDefault();
    setInterviewError("");
    setIsGeneratingInterview(true);
    const form = new FormData(event.currentTarget);
    const resumeId = String(form.get("resume") || "");

    try {
      const interview = await requestJson("/interviews/generate/", {
        method: "POST",
        token: accessToken,
        body: JSON.stringify({
          resume: Number(resumeId),
          target_role: String(form.get("target_role") || "").trim(),
          interview_type: String(form.get("interview_type") || ""),
          difficulty: String(form.get("difficulty") || ""),
          total_questions: Number(form.get("total_questions")),
          ai_consent: generationAiConsent,
        }),
      });
      setInterviews((current) => [interview, ...current]);
      await loadInterview(interview.id);
    } catch (error) {
      setInterviewError(error.message);
    } finally {
      setIsGeneratingInterview(false);
      setGenerationAiConsent(false);
    }
  }

  async function handleStartInterview() {
    if (!selectedInterview) {
      return;
    }
    setInterviewError("");
    setIsStartingInterview(true);
    try {
      const interview = await requestJson(
        `/interviews/${selectedInterview.id}/start/`,
        { method: "POST", token: accessToken },
      );
      setSelectedInterview(interview);
      setInterviews((current) =>
        current.map((item) =>
          item.id === interview.id ? interview : item,
        ),
      );
    } catch (error) {
      setInterviewError(error.message);
    } finally {
      setIsStartingInterview(false);
    }
  }

  async function handleAnswerSubmit(event) {
    event.preventDefault();
    if (!selectedInterview) {
      return;
    }
    const question =
      interviewQuestions[selectedInterview.current_question];
    if (!question) {
      setInterviewError("There is no unanswered question in this session.");
      return;
    }

    setInterviewError("");
    setIsSubmittingAnswer(true);
    try {
      await requestJson(`/interviews/questions/${question.id}/answer/`, {
        method: "POST",
        token: accessToken,
        body: JSON.stringify({
          answer_text: answerText.trim(),
          ai_consent: answerAiConsent,
        }),
      });
      setAnswerAiConsent(false);
      const interview = await loadInterview(selectedInterview.id);
      setInterviews((current) =>
        current.map((item) =>
          item.id === interview.id ? interview : item,
        ),
      );
    } catch (error) {
      setInterviewError(error.message);
    } finally {
      setIsSubmittingAnswer(false);
      setAnswerAiConsent(false);
    }
  }

  if (authChecking) {
    return (
      <main className="auth-page">
        <p className="loading-message">Loading your SmartHire workspace...</p>
      </main>
    );
  }

  if (!accessToken) {
    return (
      <main className="auth-page">
        <a className="auth-brand" href="/" aria-label="SmartHire AI home">
          <span className="brand-mark">S</span>
          <span>
            SmartHire<span className="brand-light"> AI</span>
          </span>
        </a>
        <section className="auth-card">
          <p className="eyebrow">CANDIDATE WORKSPACE</p>
          <h1>
            {authMode === "login"
              ? "Welcome back."
              : "Create your candidate account."}
          </h1>
          <p className="auth-description">
            {authMode === "login"
              ? "Sign in to continue preparing for your next interview."
              : "Set up your account to organize your interview preparation."}
          </p>

          <form className="auth-form" onSubmit={handleAuthSubmit}>
            {authMode === "register" && (
              <>
                <label>
                  First name
                  <input
                    autoComplete="given-name"
                    name="first_name"
                    required
                  />
                </label>
                <label>
                  Last name
                  <input
                    autoComplete="family-name"
                    name="last_name"
                    required
                  />
                </label>
                <label>
                  Email
                  <input
                    autoComplete="email"
                    name="email"
                    type="email"
                    required
                  />
                </label>
              </>
            )}
            <label>
              Username
              <input
                autoComplete="username"
                name="username"
                required
              />
            </label>
            <label>
              Password
              <span className="password-input-wrap">
                <input
                  autoComplete={
                    authMode === "login" ? "current-password" : "new-password"
                  }
                  minLength={8}
                  name="password"
                  type={showPassword ? "text" : "password"}
                  required
                />
                <button
                  aria-label={showPassword ? "Hide password" : "Show password"}
                  aria-pressed={showPassword}
                  className="password-toggle"
                  onClick={() => setShowPassword((visible) => !visible)}
                  type="button"
                >
                  {showPassword ? "Hide" : "Show"}
                </button>
              </span>
            </label>
            {authError && (
              <p className="form-message error" role="alert">
                {authError}
              </p>
            )}
            <button className="primary-button" disabled={isSubmitting}>
              {isSubmitting
                ? "Please wait..."
                : authMode === "login"
                  ? "Sign in"
                  : "Create account"}
            </button>
          </form>

          <p className="auth-switch">
            {authMode === "login"
              ? "New to SmartHire AI?"
              : "Already have an account?"}{" "}
            <button
              className="text-button"
              onClick={() => {
                setAuthMode(authMode === "login" ? "register" : "login");
                setAuthError("");
              }}
              type="button"
            >
              {authMode === "login" ? "Create an account" : "Sign in"}
            </button>
          </p>
        </section>
        <p className="auth-footnote">
          Candidate accounts are created with the candidate role.
        </p>
      </main>
    );
  }

  const displayName =
    [profile?.first_name, profile?.last_name].filter(Boolean).join(" ") ||
    profile?.username ||
    "Candidate";
  const initials = displayName
    .split(/\s+/)
    .slice(0, 2)
    .map((part) => part[0])
    .join("")
    .toUpperCase();

  return (
    <div className="app-shell">
      <aside className="sidebar">
        <a className="brand" href="#overview" aria-label="SmartHire AI home">
          <span className="brand-mark">S</span>
          <span>
            SmartHire<span className="brand-light"> AI</span>
          </span>
        </a>
        <p className="nav-label">WORKSPACE</p>
        <nav aria-label="Candidate workspace">
          <a className="nav-link active" href="#overview">
            Overview
          </a>
          <a className="nav-link" href="#resume">
            My resume
          </a>
          <a className="nav-link" href="#workflow">
            Interview plan
          </a>
          <a className="nav-link" href="#practice">
            Practice interviews
          </a>
        </nav>
        <div className="sidebar-note">
          <span className="status-dot" />
          <span>Interview preparation</span>
        </div>
      </aside>

      <main className="main-content" id="overview">
        <header className="topbar">
          <span className="breadcrumb">Candidate workspace / Overview</span>
          <div className="topbar-actions">
            <div className="user-chip">
              <span className="avatar">{initials}</span>
              <span>{displayName}</span>
            </div>
            <button className="text-button" onClick={handleSignOut}>
              Sign out
            </button>
          </div>
        </header>

        <section className="welcome">
          <div>
            <p className="eyebrow">YOUR PREPARATION, IN ONE PLACE</p>
            <h1>Build confidence, one interview at a time.</h1>
            <p className="welcome-copy">
              Turn your resume and target role into a guided practice session.
            </p>
          </div>
          <span className="role-badge">Candidate</span>
        </section>

        <section className="summary-grid" aria-label="Candidate summary">
          <article className="summary-card">
            <span className="card-icon purple">P</span>
            <p className="card-label">Profile status</p>
            <h2>{displayName}</h2>
            <p className="muted">{profile?.email}</p>
          </article>
          <article className="summary-card" id="resume">
            <span className="card-icon green">R</span>
            <p className="card-label">Resume library</p>
            <h2>
              {resumes.length
                ? `${resumes.length} resume${resumes.length === 1 ? "" : "s"} uploaded`
                : "No resume uploaded"}
            </h2>
            <p className="muted">PDF files up to 10 MB are supported.</p>
          </article>
          <article className="summary-card">
            <span className="card-icon orange">I</span>
            <p className="card-label">Interview practice</p>
            <h2>
              {interviews.length
                ? `${interviews.length} practice session${interviews.length === 1 ? "" : "s"}`
                : "Ready when you are"}
            </h2>
            <p className="muted">Generate a role-specific interview below.</p>
          </article>
        </section>

        {dashboardError && (
          <p className="form-message error dashboard-message" role="alert">
            {dashboardError}
          </p>
        )}

        <section className="content-grid">
          <article className="panel workflow-panel" id="workflow">
            <div className="panel-heading">
              <div>
                <p className="eyebrow">GETTING STARTED</p>
                <h2>Your preparation workflow</h2>
              </div>
              <span className="step-count">4 steps</span>
            </div>
            <ol className="workflow-list">
              {workflow.map((step) => (
                <li className="workflow-item" key={step.number}>
                  <span className="step-number">{step.number}</span>
                  <div className="step-copy">
                    <h3>{step.title}</h3>
                    <p>{step.description}</p>
                  </div>
                  <span
                    className={
                      step.status === "In place"
                        ? "step-status complete"
                        : "step-status"
                    }
                  >
                    {step.status}
                  </span>
                </li>
              ))}
            </ol>
          </article>

          <article className="panel resume-panel">
            <div className="panel-heading">
              <div>
                <p className="eyebrow">RESUME LIBRARY</p>
                <h2>Add your resume</h2>
              </div>
              <span className="upload-icon" aria-hidden="true">
                ↑
              </span>
            </div>
            <form className="resume-upload-form" onSubmit={handleResumeUpload}>
              <label className="file-picker">
                <span>{selectedFile?.name || "Choose a PDF file"}</span>
                <input
                  accept=".pdf,application/pdf"
                  onChange={(event) =>
                    setSelectedFile(event.target.files?.[0] || null)
                  }
                  ref={fileInputRef}
                  type="file"
                />
              </label>
              <p className="muted">PDF files only, up to 10 MB.</p>
              <button
                className="primary-button upload-button"
                disabled={!selectedFile || isUploading}
              >
                {isUploading ? "Uploading..." : "Upload PDF"}
              </button>
            </form>
            <label className="consent-field">
              <input
                checked={resumeAiConsent}
                onChange={(event) => setResumeAiConsent(event.target.checked)}
                type="checkbox"
              />
              <span>
                I consent to send this resume's text, with best-effort
                redaction, to Google Gemini for profile extraction. Google
                may use submitted content and responses from unpaid API usage
                to improve its products and services; human reviewers may
                process them. Do not send sensitive, confidential, or personal
                information; redaction is not guaranteed.
              </span>
            </label>
            <p className="muted">
              Without consent, extraction runs locally and resume text is not
              sent to Google. Uploading stores the PDF on this backend. Review
              Google's{" "}
              <a
                href="https://ai.google.dev/gemini-api/docs/terms"
                rel="noreferrer"
                target="_blank"
              >
                current Gemini API terms
              </a>
              .
            </p>
            {resumes.length > 0 && (
              <ul className="resume-list" aria-label="Uploaded resumes">
                {resumes.map((resume) => (
                  <li className="resume-item" key={resume.id}>
                    <div>
                      <strong>Resume #{resume.id}</strong>
                      <span>
                        Uploaded{" "}
                        {new Date(resume.uploaded_at).toLocaleDateString()}
                      </span>
                      {resume.extracted_skills?.length > 0 && (
                        <span className="skill-summary">
                          Skills: {resume.extracted_skills.join(", ")}
                        </span>
                      )}
                      {resume.extraction_source && (
                        <span className="source-badge">
                          {aiSourceLabel(resume.extraction_source)}
                        </span>
                      )}
                      {resume.extracted_qualifications?.length > 0 && (
                        <span className="skill-summary">
                          Qualifications:{" "}
                          {resume.extracted_qualifications.join(", ")}
                        </span>
                      )}
                      {resume.extracted_experience?.length > 0 && (
                        <span className="skill-summary">
                          Experience:{" "}
                          {resume.extracted_experience
                            .map((item) =>
                              [
                                item.role,
                                item.organization,
                                ...item.highlights,
                              ]
                                .filter(Boolean)
                                .join(" — "),
                            )
                            .join("; ")}
                        </span>
                      )}
                      {resume.extracted_projects?.length > 0 && (
                        <span className="skill-summary">
                          Projects:{" "}
                          {resume.extracted_projects
                            .map((item) =>
                              [
                                item.name,
                                item.description,
                                item.technologies.join(", "),
                              ]
                                .filter(Boolean)
                                .join(" — "),
                            )
                            .join("; ")}
                        </span>
                      )}
                    </div>
                    <div className="resume-actions">
                      <button
                        className="text-button"
                        disabled={
                          extractingResumeId === resume.id
                        }
                        onClick={() =>
                          handleResumeSkillExtraction(resume.id)
                        }
                        type="button"
                      >
                        {extractingResumeId === resume.id
                          ? "Analyzing..."
                          : resume.skills_extracted_at
                            ? resumeAiConsent
                              ? "Refresh skills"
                              : "Refresh locally"
                            : resumeAiConsent
                              ? "Extract skills"
                              : "Extract locally"}
                      </button>
                      <button
                        className="text-button"
                        onClick={() => handleResumeDownload(resume.id)}
                        type="button"
                      >
                        Download
                      </button>
                      <button
                        className="text-button danger-button"
                        onClick={() => handleResumeDelete(resume.id)}
                        type="button"
                      >
                        Delete
                      </button>
                    </div>
                  </li>
                ))}
              </ul>
            )}
          </article>
        </section>

        <section className="panel interview-panel" id="practice">
          <div className="panel-heading">
            <div>
              <p className="eyebrow">AI INTERVIEW PRACTICE</p>
              <h2>Create a tailored session</h2>
            </div>
            <span className="step-count">Resume to questions</span>
          </div>

          <div className="interview-layout">
            <form
              className="interview-form"
              onSubmit={handleInterviewCreate}
            >
              <label>
                Resume
                <select defaultValue="" name="resume" required>
                  <option disabled value="">
                    Select a resume
                  </option>
                  {resumes.map((resume) => (
                    <option key={resume.id} value={resume.id}>
                      Resume #{resume.id}
                    </option>
                  ))}
                </select>
              </label>
              <label>
                Target role
                <input
                  defaultValue="General"
                  maxLength={120}
                  name="target_role"
                  required
                />
              </label>
              <div className="interview-form-row">
                <label>
                  Interview type
                  <select defaultValue="TECHNICAL" name="interview_type">
                    <option value="TECHNICAL">Technical</option>
                    <option value="HR">HR</option>
                    <option value="BEHAVIORAL">Behavioral</option>
                    <option value="APTITUDE">Aptitude</option>
                  </select>
                </label>
                <label>
                  Difficulty
                  <select defaultValue="MEDIUM" name="difficulty">
                    <option value="EASY">Beginner</option>
                    <option value="MEDIUM">Intermediate</option>
                    <option value="HARD">Advanced</option>
                  </select>
                </label>
              </div>
              <label>
                Number of questions
                <select defaultValue="5" name="total_questions">
                  {[3, 5, 7, 10].map((count) => (
                    <option key={count} value={count}>
                      {count} questions
                    </option>
                  ))}
                </select>
              </label>
              <p className="muted">
                Questions are tailored from your resume skills and chosen role.
              </p>
              <label className="consent-field">
                <input
                  checked={generationAiConsent}
                  onChange={(event) =>
                    setGenerationAiConsent(event.target.checked)
                  }
                  type="checkbox"
                />
                <span>
                  I consent to send my selected role, resume-derived skills,
                  relevant project descriptions and experience highlights,
                  and earlier generated questions to Google Gemini. Resume
                  text may also be sent if needed for extraction, with
                  best-effort redaction. Google may use
                  submitted content and responses from unpaid API usage to
                  improve its products and services; human reviewers may
                  process them. Do not include sensitive, confidential, or
                  personal information; redaction is not guaranteed.
                </span>
              </label>
              <p className="muted">
                Without consent, questions are generated locally from
                deterministic templates; interview details are not sent to
                Google. Review Google's{" "}
                <a
                  href="https://ai.google.dev/gemini-api/docs/terms"
                  rel="noreferrer"
                  target="_blank"
                >
                  current Gemini API terms
                </a>
                .
              </p>
              <button
                className="primary-button"
                disabled={
                  !resumes.length ||
                  isGeneratingInterview
                }
              >
                {isGeneratingInterview
                  ? "Generating questions..."
                  : "Generate interview"}
              </button>
              {!resumes.length && (
                <p className="muted">
                  Upload a resume first to create a tailored interview.
                </p>
              )}
            </form>

            <div className="interview-history">
              <h3>Your sessions</h3>
              {interviews.length ? (
                <ul className="interview-list">
                  {interviews.map((interview) => (
                    <li className="interview-item" key={interview.id}>
                      <div>
                        <strong>{interview.target_role}</strong>
                        <span>
                          {interview.interview_type} · {interview.difficulty}
                        </span>
                        <span>
                          {interview.status.replaceAll("_", " ")}
                        </span>
                        {interview.generation_source && (
                          <span className="source-badge">
                            {aiSourceLabel(interview.generation_source)}
                          </span>
                        )}
                      </div>
                      <button
                        className="text-button"
                        onClick={() => handleOpenInterview(interview.id)}
                        type="button"
                      >
                        {interview.status === "COMPLETED"
                          ? "Review"
                          : "Open"}
                      </button>
                    </li>
                  ))}
                </ul>
              ) : (
                <p className="muted">
                  Generated sessions will appear here.
                </p>
              )}
            </div>
          </div>

          {interviewError && (
            <p className="form-message error" role="alert">
              {interviewError}
            </p>
          )}

          {selectedInterview && (
            <section className="interview-room" aria-live="polite">
              <div>
                <p className="eyebrow">INTERVIEW ROOM</p>
                <h3>{selectedInterview.target_role}</h3>
                <p className="muted">
                  {selectedInterview.interview_type} ·{" "}
                  {selectedInterview.difficulty} ·{" "}
                  {selectedInterview.status.replaceAll("_", " ")}
                </p>
                {selectedInterview.generation_source && (
                  <span className="source-badge">
                    {aiSourceLabel(selectedInterview.generation_source)}
                  </span>
                )}
              </div>

              {interviewQuestions
                .filter((question) => question.answer)
                .map((question) => (
                  <article
                    className="evaluation-card"
                    key={question.id}
                  >
                    <div className="panel-heading">
                      <h4>{question.question_text}</h4>
                      {question.answer.evaluation_source && (
                        <span className="source-badge">
                          {aiSourceLabel(question.answer.evaluation_source)}
                        </span>
                      )}
                    </div>
                    {question.answer.evaluation ? (
                      <>
                        <p className="muted">
                          {question.answer.evaluation.overall_feedback}
                        </p>
                        {question.expected_criteria?.length > 0 && (
                          <p className="muted">
                            Criteria considered:{" "}
                            {question.expected_criteria.join("; ")}
                          </p>
                        )}
                        <div className="evaluation-grid">
                          {[
                            ["correctness", "Correctness"],
                            ["relevance", "Relevance"],
                            ["clarity", "Clarity"],
                            ["completeness", "Completeness"],
                          ].map(([key, label]) => {
                            const dimension =
                              question.answer.evaluation[key];
                            return (
                              <div key={key}>
                                <strong>
                                  {label}: {dimension.score}/5
                                </strong>
                                <p className="muted">{dimension.feedback}</p>
                              </div>
                            );
                          })}
                        </div>
                        {question.answer.evaluation.improvement_suggestions
                          ?.length > 0 && (
                          <p className="muted">
                            Suggestions:{" "}
                            {question.answer.evaluation.improvement_suggestions.join(
                              " ",
                            )}
                          </p>
                        )}
                      </>
                    ) : (
                      <p className="muted">
                        Your answer was saved without being sent to Gemini, so
                        no AI feedback was generated.
                      </p>
                    )}
                    {question.answer.evaluation && (
                      <p className="evaluation-disclaimer">
                        Practice feedback only. This score is subjective and
                        is not an objective or definitive measure of candidate
                        ability.
                      </p>
                    )}
                  </article>
                ))}

              {selectedInterview.status === "CREATED" && (
                <button
                  className="primary-button"
                  disabled={isStartingInterview}
                  onClick={handleStartInterview}
                  type="button"
                >
                  {isStartingInterview ? "Starting..." : "Start interview"}
                </button>
              )}

              {selectedInterview.status === "IN_PROGRESS" && (
                <form
                  className="answer-form"
                  onSubmit={handleAnswerSubmit}
                >
                  {interviewQuestions[
                    selectedInterview.current_question
                  ] ? (
                    <>
                      <p className="question-count">
                        Question {selectedInterview.current_question + 1} of{" "}
                        {interviewQuestions.length}
                      </p>
                      <h4>
                        {
                          interviewQuestions[
                            selectedInterview.current_question
                          ].question_text
                        }
                      </h4>
                      <p className="muted">
                        Topic:{" "}
                        {
                          interviewQuestions[
                            selectedInterview.current_question
                          ].topic
                        }{" "}
                        ·{" "}
                        {
                          interviewQuestions[
                            selectedInterview.current_question
                          ].difficulty
                        }
                      </p>
                      <label>
                        Your answer
                        <textarea
                          onChange={(event) =>
                            setAnswerText(event.target.value)
                          }
                          required
                          rows={5}
                          value={answerText}
                        />
                      </label>
                      <label className="consent-field">
                        <input
                          checked={answerAiConsent}
                          onChange={(event) =>
                            setAnswerAiConsent(event.target.checked)
                          }
                          type="checkbox"
                        />
                        <span>
                          Optional: I consent to send this answer and its
                          question, with best-effort redaction, to Google
                          Gemini for practice feedback. Google may use
                          submitted content and responses from unpaid API
                          usage to improve its products and services; human
                          reviewers may process them. Do not include
                          sensitive, confidential, or personal information;
                          redaction is not guaranteed.
                        </span>
                      </label>
                      <p className="muted">
                        Leave unchecked for local heuristic feedback; your
                        answer is saved here but not sent to Google.
                        {" "}Review Google's{" "}
                        <a
                          href="https://ai.google.dev/gemini-api/docs/terms"
                          rel="noreferrer"
                          target="_blank"
                        >
                          current Gemini API terms
                        </a>
                        .
                      </p>
                      <button
                        className="primary-button"
                        disabled={
                          isSubmittingAnswer ||
                          !answerText.trim()
                        }
                      >
                        {isSubmittingAnswer
                          ? "Saving answer..."
                          : "Submit answer"}
                      </button>
                    </>
                  ) : (
                    <p className="muted">
                      No unanswered questions remain in this session.
                    </p>
                  )}
                </form>
              )}

              {selectedInterview.status === "COMPLETED" && (
                <p className="completion-message">
                  You completed all {interviewQuestions.length} questions in
                  this session.
                </p>
              )}
            </section>
          )}
        </section>

        <footer className="page-footer">
          <span>SmartHire AI</span>
          <span>Candidate preparation workspace</span>
        </footer>
      </main>
    </div>
  );
}

export default App;
