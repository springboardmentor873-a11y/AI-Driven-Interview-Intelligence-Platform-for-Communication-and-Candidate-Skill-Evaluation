function aiSourceLabel(source) {
  if (source === "gemini") {
    return "Generated by Gemini";
  }
  if (source === "fallback") {
    return "Local deterministic fallback";
  }
  if (source === "not_evaluated") {
    return "Not evaluated";
  }
  return "";
}

function apiError(data, status) {
  const messages = [];
  if (typeof data?.detail === "string") {
    messages.push(data.detail);
  } else if (data && typeof data === "object") {
    Object.values(data).forEach((value) => {
      messages.push(...(Array.isArray(value) ? value : [value]));
    });
  }

  const error = new Error(
    messages.filter((message) => typeof message === "string").join(" ") ||
      `Request failed with status ${status}.`,
  );
  error.status = status;
  return error;
}

async function requestJson(path, { method = "GET", token, body } = {}) {
  const headers = {};

  if (token) {
    headers.Authorization = `Bearer ${token}`;
  }
  if (body && !(body instanceof FormData)) {
    headers["Content-Type"] = "application/json";
  }

  const response = await fetch(`${API_BASE_URL}${path}`, {
    method,
    headers,
    body,
  });
  const data = await response.json().catch(() => null);

  if (!response.ok) {
    throw apiError(data, response.status);
  }

  return data;
}

function uploadJsonWithProgress(
  path,
  { token, body, onProgress },
) {
  return new Promise((resolve, reject) => {
    const request = new XMLHttpRequest();
    request.open("POST", `${API_BASE_URL}${path}`);
    if (token) {
      request.setRequestHeader("Authorization", `Bearer ${token}`);
    }
    request.upload.addEventListener("progress", (event) => {
      if (event.lengthComputable) {
        onProgress(Math.round((event.loaded / event.total) * 100));
      }
    });
    request.addEventListener("load", () => {
      let data = null;
      try {
        data = JSON.parse(request.responseText);
      } catch {
        data = null;
      }
      if (request.status < 200 || request.status >= 300) {
        reject(apiError(data, request.status));
        return;
      }
      onProgress(100);
      resolve(data);
    });
    request.addEventListener("error", () => {
      reject(new Error("Network error while uploading the resume."));
    });
    request.addEventListener("abort", () => {
      reject(new Error("Resume upload was canceled."));
    });
    request.send(body);
  });
}

